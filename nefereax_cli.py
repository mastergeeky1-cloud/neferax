def check_tool(tool_name):
    """Returns (installed, needs_sudo, binary_name)"""
    if tool_name not in TOOLS:
        return False, False, None
    cmd = TOOLS[tool_name]["cmd"].split()[0]
    cmd = cmd.split("|")[0].strip()
    bin_found = shutil.which(cmd) is not None
    needs_sudo = tool_name in SUDO_REQUIRED
    return bin_found, needs_sudo, cmd

# ── Tool Execution ─────────────────────────────────────────────────────
def run(tool_name, target="", desc=None):
    if tool_name not in TOOLS:
        log("-", f"Unknown tool: {tool_name}")
        return -1, 0

    info = TOOLS[tool_name]
    raw_cmd = info["cmd"]
    cmd = raw_cmd.replace("<target>",target).replace("<domain>",target).replace("<url>",target)

    installed, needs_sudo, binary = check_tool(tool_name)

    if not installed and binary:
        log("!", f"'{binary}' not installed. Install: sudo apt install {binary}")
        return -1, 0

    if needs_sudo and os.geteuid() != 0:
        log("*", f"Requires root — prepending sudo")
        cmd = f"sudo {cmd}"

    print(f"  {R}\u2554{'\u2550'*BW}\u2557{X}")
    header = desc or f"{tool_name} on {target or '(no target)'}"
    print(f"  {R}\u2551  {S(header)}{' '*(BW - len(header) - 4)}{R}\u2551{X}")
    print(f"  {R}\u2551  {D}{cmd}{X}{' '*(BW - len(cmd) - 4)}{R}\u2551{X}")
    print(f"  {R}\u255a{'\u2550'*BW}\u255d{X}")

    start = time.time()
    stdout_buf = []
    stderr_buf = []
    exit_code = 0
    try:
        p = subprocess.Popen(cmd, shell=True, stdout=subprocess.PIPE,
                             stderr=subprocess.PIPE, universal_newlines=True, bufsize=1)
        for line in p.stdout:
            print(f"  {W}  {line}", end='')
            stdout_buf.append(line)
        for line in p.stderr:
            stderr_buf.append(line)
        p.wait()
        exit_code = p.returncode
    except KeyboardInterrupt:
        log("!", "Interrupted by user")
        exit_code = -1
    except Exception as e:
        log("-", str(e))
        exit_code = -1

    duration_ms = (time.time() - start) * 1000

    if exit_code == 0:
        log("+", f"Done ({_timefmt(duration_ms)})")
    else:
        log("!" if exit_code != -1 else "*", f"Exit: {exit_code} ({_timefmt(duration_ms)})")

    # Generate HTML report
    stdout_str = "".join(stdout_buf)
    stderr_str = "".join(stderr_buf)
    rpath = write_tool_report(tool_name, target or "(none)", cmd, stdout_str, stderr_str,
                              exit_code, duration_ms, info.get("methods"))
    log("*", f"Report: {rpath}")
    write_report_index()

    return exit_code, duration_ms, str(rpath)

