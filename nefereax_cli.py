# ── Chain Runner ───────────────────────────────────────────────────────
def run_chain(name, target):
    chain = CHAINS.get(name)
    if not chain: return
    logo()
    box_start(f"{name.upper()}  \u2502 {chain[0]}  \u2502 {S(target,G)}")
    start = time.time()
    results = []

    for tool_name in chain[1]:
        if tool_name not in TOOLS: continue
        cmd = TOOLS[tool_name]["cmd"].replace("<target>",target).replace("<domain>",target).replace("<url>",target)
        ec, dur, rp = run(tool_name, target, f"Running {tool_name} on {target}")
        print()
        results.append({"tool": tool_name, "target": target, "exit_code": ec,
                        "duration_ms": dur, "report_path": rp})

    if name == "brute":
        for svc in ["ssh","ftp","http-post-form","mysql","smb"]:
            c = f"hydra -l root -P /usr/share/wordlists/rockyou.txt.gz {target} {svc}"
            ec, dur, rp = run("hydra", target, f"Brute forcing {svc} on {target}")
            print()
            results.append({"tool": f"hydra-{svc}", "target": target, "exit_code": ec,
                            "duration_ms": dur, "report_path": rp})

    if name == "full":
        for sub in ["recon","web","exploit","brute"]:
            run_chain(sub, target)

    elapsed = (time.time() - start) * 1000
    box_end()
    log("+", f"Chain '{name}' completed in {_timefmt(elapsed)}")

    # Generate final chain report
    if results:
        rpath = write_chain_report(name, target, results)
        write_report_index()
        log("*", f"Chain report: {rpath}")
    box_end()

