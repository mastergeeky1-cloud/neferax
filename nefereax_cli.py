def do_search(query, method=None):
    found = [(n, v) for n, v in TOOLS.items()
             if query in n.lower() or query in v["desc"].lower() or query in v["cmd"].lower() or query in v["cat"]]
    if method:
        found = [(n, v) for n, v in found if method.lower() in [m.lower() for m in v.get("methods", [])]]
    logo()
    box_start(f"SEARCH  {D}for '{query}'{f'  method:{method}' if method else ''}{X}")
